#!/usr/bin/env python3
"""Generate src/lib/db/schema-map.ts from the catalog export.

The query builder uses this to resolve PostgREST-style embeds (FK direction and
target column), default upsert conflict targets (primary keys), jsonb
serialisation and generated columns that must never be written.
"""
import json
import re
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
cat = json.loads((root / "migration-artifacts" / "dumps" / "_catalog.json").read_text())[0]["cat"]

fk_re = re.compile(r"FOREIGN KEY \(([^)]*)\) REFERENCES (?:public\.)?([a-z_0-9]+)\(([^)]*)\)")
pk_re = re.compile(r"PRIMARY KEY \(([^)]*)\)")

fks: dict[str, list[tuple[str, str, str, str]]] = {}
pks: dict[str, list[str]] = {}
for con in cat["constraints"]:
    table = con["table"].split(".")[-1]
    if con["type"] == "f":
        m = fk_re.match(con["def"])
        if not m or con["def"].split("REFERENCES ")[1].startswith("auth."):
            continue
        cols = [c.strip() for c in m.group(1).split(",")]
        dst_cols = [c.strip() for c in m.group(3).split(",")]
        if len(cols) != 1:
            continue  # composite FKs are never embedded by the app
        fks.setdefault(table, []).append((cols[0], m.group(2), dst_cols[0], con["name"]))
    elif con["type"] == "p":
        m = pk_re.match(con["def"])
        if m:
            pks[table] = [c.strip() for c in m.group(1).split(",")]

jsonb: dict[str, list[str]] = {}
generated: dict[str, list[str]] = {}
for t in cat["tables"]:
    for c in t["columns"]:
        if c["udt"] in ("jsonb", "json"):
            jsonb.setdefault(t["name"], []).append(c["name"])
        if c["generated"] == "s":
            generated.setdefault(t["name"], []).append(c["name"])


def ts_set_map(name: str, data: dict[str, list[str]]) -> list[str]:
    lines = [f"export const {name}: Record<string, ReadonlySet<string>> = {{"]
    for k in sorted(data):
        vals = ", ".join(json.dumps(v) for v in sorted(data[k]))
        lines.append(f"  {k}: new Set([{vals}]),")
    lines.append("};")
    return lines


out = [
    "// Generated by scripts/migration/build-schema-map.py from the live schema — do not hand-edit.",
    "",
    "export interface FkEdge {",
    "  column: string;",
    "  foreignTable: string;",
    "  foreignColumn: string;",
    "  constraint: string;",
    "}",
    "",
    "export const FK_MAP: Record<string, FkEdge[]> = {",
]
for t in sorted(fks):
    out.append(f"  {t}: [")
    for col, dst, dcol, name in sorted(fks[t]):
        out.append(
            f"    {{ column: {json.dumps(col)}, foreignTable: {json.dumps(dst)}, "
            f"foreignColumn: {json.dumps(dcol)}, constraint: {json.dumps(name)} }},"
        )
    out.append("  ],")
out.append("};")
out.append("")
out.append("export const PRIMARY_KEYS: Record<string, readonly string[]> = {")
for t in sorted(pks):
    out.append(f"  {t}: [{', '.join(json.dumps(c) for c in pks[t])}],")
out.append("};")
out.append("")
out += ts_set_map("JSONB_COLUMNS", jsonb)
out.append("")
out += ts_set_map("GENERATED_COLUMNS", generated)
out.append("")

dest = root / "src" / "lib" / "db" / "schema-map.ts"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(out))
print(f"{dest}: {sum(len(v) for v in fks.values())} FK edges, {len(pks)} PKs, "
      f"{sum(len(v) for v in jsonb.values())} json cols, {sum(len(v) for v in generated.values())} generated")
