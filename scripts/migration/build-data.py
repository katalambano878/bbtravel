#!/usr/bin/env python3
"""Build data.sql (all rows from the Supabase snapshot) and checksum.sql.

data.sql loads every table with json_populate_recordset so values round-trip
exactly (numeric, timestamptz, arrays, jsonb). It runs with
session_replication_role = replica — like pg_dump --disable-triggers — so
side-effect triggers (petty-cash balances, invoice totals) do not re-apply
historical rows. Referential integrity is verified afterwards by verify.sql.

checksum.sql prints one md5 per table over the canonical jsonb text of every
row; run it on Supabase and on the target and diff the output.
"""
import json
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
dumps = root / "migration-artifacts" / "dumps"
cat = json.loads((dumps / "_catalog.json").read_text())[0]["cat"]
data = json.loads((dumps / "data.json").read_text())


def qi(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def dollar(payload: str) -> str:
    tag = "bbdata"
    n = 0
    while f"${tag}{n}$" in payload:
        n += 1
    return f"${tag}{n}${payload}${tag}{n}$"


def insert(table_sql: str, columns: list[str], rows: list) -> str:
    if not rows:
        return f"-- {table_sql}: 0 rows"
    cols = ", ".join(qi(c) for c in columns)
    return (
        f"INSERT INTO {table_sql} ({cols})\n"
        f"SELECT {cols} FROM json_populate_recordset(NULL::{table_sql}, {dollar(json.dumps(rows))}::json);"
    )


out = [
    "-- Generated by scripts/migration/build-data.py — contains customer data, never commit.",
    "\\set ON_ERROR_STOP on",
    "BEGIN;",
    "SET session_replication_role = replica;",
    "SET TIME ZONE 'UTC';",
]

auth_cols = [c["name"] for c in cat["auth_users_columns"] if c["generated"] != "s"]
out.append(insert("auth.users", auth_cols, data["__auth_users"]))

for t in cat["tables"]:
    cols = [c["name"] for c in t["columns"] if c["generated"] != "s"]
    out.append(insert(f"public.{qi(t['name'])}", cols, data[t["name"]]))

out += ["SET session_replication_role = origin;", "COMMIT;"]
(dumps / "data.sql").write_text("\n".join(out) + "\n")

# --- checksum.sql -----------------------------------------------------------
tables = [("auth", "users")] + [("public", t["name"]) for t in cat["tables"]]
parts = []
for schema, name in tables:
    fq = f"{schema}.{qi(name)}"
    parts.append(
        f"select '{schema}.{name}' as t, count(*) as n, "
        f"coalesce(md5(string_agg(to_jsonb(x)::text, '|' order by to_jsonb(x)::text)), '-') as h from {fq} x"
    )
checksum = "SET TIME ZONE 'UTC';\n" + "\nunion all\n".join(parts) + "\norder by 1;\n"
(dumps / "checksum.sql").write_text(checksum)

# --- verify.sql: every FK holds (catches anything replica mode let through) ---
fk_checks = []
for con in cat["constraints"]:
    if con["type"] != "f":
        continue
    fk_checks.append(con)
verify = ["SET TIME ZONE 'UTC';"]
verify.append(
    "DO $$ DECLARE r record; bad bigint; total int := 0; BEGIN\n"
    "  FOR r IN SELECT conrelid::regclass AS src, conname, pg_get_constraintdef(oid) AS def,\n"
    "             conkey, confkey, confrelid::regclass AS dst\n"
    "      FROM pg_constraint WHERE contype = 'f' AND connamespace = 'public'::regnamespace LOOP\n"
    "    EXECUTE format(\n"
    "      'SELECT count(*) FROM %s s WHERE (%s) IS NOT NULL AND NOT EXISTS (SELECT 1 FROM %s d WHERE (%s) = (%s))',\n"
    "      r.src,\n"
    "      (SELECT string_agg(format('s.%I', attname), ',') FROM pg_attribute WHERE attrelid = r.src AND attnum = ANY(r.conkey)),\n"
    "      r.dst,\n"
    "      (SELECT string_agg(format('d.%I', attname), ',') FROM unnest(r.confkey) WITH ORDINALITY k(n, i) JOIN pg_attribute ON attrelid = r.dst AND attnum = k.n),\n"
    "      (SELECT string_agg(format('s.%I', attname), ',') FROM unnest(r.conkey) WITH ORDINALITY k(n, i) JOIN pg_attribute ON attrelid = r.src AND attnum = k.n)\n"
    "    ) INTO bad;\n"
    "    total := total + 1;\n"
    "    IF bad > 0 THEN RAISE WARNING 'FK VIOLATION % on %: % rows', r.conname, r.src, bad; END IF;\n"
    "  END LOOP;\n"
    "  RAISE NOTICE 'checked % foreign keys', total;\n"
    "END $$;"
)
(dumps / "verify.sql").write_text("\n".join(verify) + "\n")

rows = sum(len(data[t["name"]]) for t in cat["tables"])
print(f"data.sql: {len(cat['tables'])} tables, {rows} rows, {len(data['__auth_users'])} auth users; "
      f"checksum.sql: {len(tables)} tables; verify.sql: {len(fk_checks)} FKs")
