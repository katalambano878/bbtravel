#!/usr/bin/env python3
"""Build a plain-Postgres schema from the live Supabase catalog export.

Input:  migration-artifacts/dumps/_catalog.json  (exported via the Supabase SQL API)
Output: migration-artifacts/dumps/schema.sql

The output reproduces the public schema exactly (enums, columns, defaults,
generated columns, constraints, indexes, functions, triggers) plus a minimal
`auth` schema: the full `auth.users` table (same columns as Supabase GoTrue) and
`auth.uid()` / `auth.role()` / `auth.jwt()` shims so the existing SQL helper
functions keep compiling. Row-level-security policies and Supabase role grants
are intentionally not recreated: the app is the only database client and it
enforces access in code.
"""
import json
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
dumps = root / "migration-artifacts" / "dumps"
cat = json.loads((dumps / "_catalog.json").read_text())[0]["cat"]
APP_ROLE = sys.argv[2] if len(sys.argv) > 2 else "store_bbconsult"

out: list[str] = []
w = out.append


def qi(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def ql(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


w("-- Generated by scripts/migration/build-schema.py — do not edit by hand.")
w("\\set ON_ERROR_STOP on")
w("BEGIN;")

# --- extensions + schemas (superuser part) -----------------------------------
w("CREATE SCHEMA IF NOT EXISTS extensions;")
w('CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA extensions;')
w("CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;")
w(f"GRANT USAGE ON SCHEMA extensions TO {qi(APP_ROLE)};")
w(f"CREATE SCHEMA IF NOT EXISTS auth AUTHORIZATION {qi(APP_ROLE)};")
w(f"ALTER SCHEMA public OWNER TO {qi(APP_ROLE)};")
w(f"SET ROLE {qi(APP_ROLE)};")
w("SET search_path = public, extensions;")
w("SET check_function_bodies = off;")

# --- auth.users (same columns as Supabase) -----------------------------------
cols = []
for c in cat["auth_users_columns"]:
    if c["generated"] == "s":
        cols.append(f"  {qi(c['name'])} {c['type']} GENERATED ALWAYS AS ({c['default']}) STORED")
        continue
    line = f"  {qi(c['name'])} {c['type']}"
    if c["default"] is not None:
        line += f" DEFAULT {c['default']}"
    if c["notnull"]:
        line += " NOT NULL"
    cols.append(line)
cols.append("  PRIMARY KEY (id)")
w("CREATE TABLE auth.users (\n" + ",\n".join(cols) + "\n);")
w("CREATE UNIQUE INDEX users_email_partial_key ON auth.users (email) WHERE (is_sso_user = false);")
w("CREATE INDEX users_instance_id_email_idx ON auth.users (instance_id, lower((email)::text));")

# Session-scoped claims shims. The app never sets these, so in-process queries
# see auth.uid() = NULL; they exist so SQL helpers keep compiling unchanged.
w("""CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  select nullif(coalesce(current_setting('request.jwt.claim.sub', true),
    (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')), '')::uuid
$$;""")
w("""CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $$
  select nullif(coalesce(current_setting('request.jwt.claim.role', true),
    (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role')), '')::text
$$;""")
w("""CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb
$$;""")

# --- enums --------------------------------------------------------------------
for e in cat["enums"]:
    labels = ", ".join(ql(x) for x in e["labels"])
    w(f"CREATE TYPE public.{qi(e['name'])} AS ENUM ({labels});")

# --- tables -------------------------------------------------------------------
for t in cat["tables"]:
    lines = []
    for c in t["columns"]:
        if c["generated"] == "s":
            lines.append(f"  {qi(c['name'])} {c['type']} GENERATED ALWAYS AS ({c['default']}) STORED")
            continue
        line = f"  {qi(c['name'])} {c['type']}"
        if c["identity"] in ("a", "d"):
            line += " GENERATED " + ("ALWAYS" if c["identity"] == "a" else "BY DEFAULT") + " AS IDENTITY"
        elif c["default"] is not None:
            line += f" DEFAULT {c['default']}"
        if c["notnull"]:
            line += " NOT NULL"
        lines.append(line)
    w(f"CREATE TABLE public.{qi(t['name'])} (\n" + ",\n".join(lines) + "\n);")

# --- constraints: PK / unique / check / exclusion first, FKs last ---------------
order = {"p": 0, "u": 1, "c": 2, "x": 3, "f": 4}
for con in sorted(cat["constraints"], key=lambda c: (order.get(c["type"], 9), c["table"], c["name"])):
    table = con["table"] if "." in con["table"] else f"public.{qi(con['table'])}"
    w(f"ALTER TABLE {table} ADD CONSTRAINT {qi(con['name'])} {con['def']};")

# --- indexes ------------------------------------------------------------------
for idx in cat["indexes"]:
    w(idx["def"] + ";")

# --- functions (skip Supabase event-trigger helper) ---------------------------
for f in cat["functions"]:
    if f["name"] == "rls_auto_enable":
        continue
    w(f["def"].rstrip() + ";")

# --- triggers -----------------------------------------------------------------
for tg in cat["triggers"]:
    w(tg["def"] + ";")
    if tg["enabled"] == "D":
        w(f"ALTER TABLE public.{qi(tg['table'])} DISABLE TRIGGER {qi(tg['name'])};")

w("RESET ROLE;")
w("COMMIT;")

(dumps / "schema.sql").write_text("\n".join(out) + "\n")
print(f"schema.sql: {len(cat['tables'])} tables, {len(cat['enums'])} enums, "
      f"{len(cat['constraints'])} constraints, {len(cat['indexes'])} indexes, "
      f"{len(cat['functions']) - 1} functions, {len(cat['triggers'])} triggers")
